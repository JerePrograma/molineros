package ar.com.ospim.liquidaciones;

public class ListasReintegrosNoEncontradasException extends Exception {

	public ListasReintegrosNoEncontradasException() {
		super();
	}

	public ListasReintegrosNoEncontradasException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ListasReintegrosNoEncontradasException(String arg0) {
		super(arg0);
	}

	public ListasReintegrosNoEncontradasException(Throwable arg0) {
		super(arg0);
	}

	private static final long serialVersionUID = 1L;

}
