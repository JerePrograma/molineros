package ar.com.ospim.liquidaciones.comprobantes;

public class ConceptoConsolidarException extends Exception {

	public ConceptoConsolidarException() {
		super();
	}

	public ConceptoConsolidarException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ConceptoConsolidarException(String arg0) {
		super(arg0);
	}

	public ConceptoConsolidarException(Throwable arg0) {
		super(arg0);
	}

	private static final long serialVersionUID = 1L;

}
