package ar.com.ospim.afiliados.exceptions;

public class FaltanTercerizadorasException extends Exception {

	private static final long serialVersionUID = 3445254806623775880L;

	public FaltanTercerizadorasException() {
		super();
	}

	public FaltanTercerizadorasException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public FaltanTercerizadorasException(String arg0) {
		super(arg0);
	}

	public FaltanTercerizadorasException(Throwable arg0) {
		super(arg0);
	}

}
