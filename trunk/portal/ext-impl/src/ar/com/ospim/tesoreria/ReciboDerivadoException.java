package ar.com.ospim.tesoreria;

public class ReciboDerivadoException extends Exception {

	private static final long serialVersionUID = 6163336766817248622L;

	public ReciboDerivadoException() {
		super();
	}

	public ReciboDerivadoException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ReciboDerivadoException(String arg0) {
		super(arg0);
	}

	public ReciboDerivadoException(Throwable arg0) {
		super(arg0);
	}

}
