package ar.com.ospim.liquidaciones;

public class ConceptoUtilizadoException extends Exception {

	private static final long serialVersionUID = -8593908613092662347L;

	public ConceptoUtilizadoException() {
		super();
	}

	public ConceptoUtilizadoException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ConceptoUtilizadoException(String arg0) {
		super(arg0);
	}

	public ConceptoUtilizadoException(Throwable arg0) {
		super(arg0);
	}

}
