package ar.com.ospim.tesoreria;

public class FaltaFechaCierreActaException extends Exception {

	private static final long serialVersionUID = 7280572680343798791L;

	public FaltaFechaCierreActaException() {
		super();
	}

	public FaltaFechaCierreActaException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public FaltaFechaCierreActaException(String arg0) {
		super(arg0);
	}

	public FaltaFechaCierreActaException(Throwable arg0) {
		super(arg0);
	}

}
