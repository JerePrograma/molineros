package ar.com.ospim.liquidaciones;

public class AnticiposUtilizadosException extends Exception {
	private static final long serialVersionUID = -3903644704759781543L;

	public AnticiposUtilizadosException() {
		super();
	}

	public AnticiposUtilizadosException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public AnticiposUtilizadosException(String arg0) {
		super(arg0);
	}

	public AnticiposUtilizadosException(Throwable arg0) {
		super(arg0);
	}

}
