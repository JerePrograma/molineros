package ar.com.ospim.global;

public class ExisteReciboConvenioException extends Exception {

	private static final long serialVersionUID = 7616728972199626528L;

	public ExisteReciboConvenioException() {
		super();
	}

	public ExisteReciboConvenioException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ExisteReciboConvenioException(String arg0) {
		super(arg0);
	}

	public ExisteReciboConvenioException(Throwable arg0) {
		super(arg0);
	}

}
