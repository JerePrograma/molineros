package ar.com.ospim.procesaArchivos.exception;

public class ErrorActualizaContratoException extends Exception {

	/**
	 * 
	 */
	private static final long serialVersionUID = 1L;

	public ErrorActualizaContratoException() {
		super();
	}

	public ErrorActualizaContratoException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ErrorActualizaContratoException(String arg0) {
		super(arg0);
	}

	public ErrorActualizaContratoException(Throwable arg0) {
		super(arg0);
	}

}
