package ar.com.ospim.autorizaciones.exceptions;

public class RevisionesReclamosException extends Exception {

	private static final long serialVersionUID = -408824551995824883L;

	public RevisionesReclamosException () {
		super();
	}

	public RevisionesReclamosException (String message, Throwable cause) {
		super(message, cause);
	}

	public RevisionesReclamosException (String message) {
		super(message);
	}

	public RevisionesReclamosException (Throwable cause) {
		super(cause);
	}

	
}
