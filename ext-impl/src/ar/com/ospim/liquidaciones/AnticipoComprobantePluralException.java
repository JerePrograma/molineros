package ar.com.ospim.liquidaciones;

public class AnticipoComprobantePluralException extends Exception {

	private static final long serialVersionUID = 849355535178748336L;

	public AnticipoComprobantePluralException() {
		super();
	}

	public AnticipoComprobantePluralException(String message, Throwable cause) {
		super(message, cause);
	}

	public AnticipoComprobantePluralException(String message) {
		super(message);
	}

	public AnticipoComprobantePluralException(Throwable cause) {
		super(cause);
	}

}
