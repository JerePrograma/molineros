package ar.com.ospim.tesoreria;

public class ActaRelacionadaException extends Exception {

	private static final long serialVersionUID = 2879636303273209080L;

	public ActaRelacionadaException() {
		super();
	}

	public ActaRelacionadaException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ActaRelacionadaException(String arg0) {
		super(arg0);
	}

	public ActaRelacionadaException(Throwable arg0) {
		super(arg0);
	}

}
