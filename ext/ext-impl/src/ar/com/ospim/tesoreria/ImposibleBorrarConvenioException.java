package ar.com.ospim.tesoreria;

public class ImposibleBorrarConvenioException extends Exception {

	private static final long serialVersionUID = 3920147786367847816L;

	public ImposibleBorrarConvenioException() {
		super();
	}

	public ImposibleBorrarConvenioException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public ImposibleBorrarConvenioException(String arg0) {
		super(arg0);
	}

	public ImposibleBorrarConvenioException(Throwable arg0) {
		super(arg0);
	}

}
