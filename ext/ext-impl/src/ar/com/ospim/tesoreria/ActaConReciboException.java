package ar.com.ospim.tesoreria;

public class ActaConReciboException extends Exception {

	private static final long serialVersionUID = 5345155087007681534L;

	public ActaConReciboException() {
		super();
	}

	public ActaConReciboException(String message, Throwable cause) {
		super(message, cause);
	}

	public ActaConReciboException(String message) {
		super(message);
	}

	public ActaConReciboException(Throwable cause) {
		super(cause);
	}

}
