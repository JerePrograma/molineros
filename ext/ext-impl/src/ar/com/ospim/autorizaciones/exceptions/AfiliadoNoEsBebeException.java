package ar.com.ospim.autorizaciones.exceptions;

public class AfiliadoNoEsBebeException extends Exception {

	private static final long serialVersionUID = 5627088136490620598L;

	public AfiliadoNoEsBebeException() {
		super();
	}

	public AfiliadoNoEsBebeException(String message, Throwable cause) {
		super(message, cause);
	}

	public AfiliadoNoEsBebeException(String message) {
		super(message);
	}

	public AfiliadoNoEsBebeException(Throwable cause) {
		super(cause);
	}

}
