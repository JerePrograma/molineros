package ar.com.ospim.afiliados.exceptions;

public class FaltanSituacionesLaboralesException extends Exception {
	private static final long serialVersionUID = 1745238505391283663L;

	public FaltanSituacionesLaboralesException() {
		super();
	}

	public FaltanSituacionesLaboralesException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public FaltanSituacionesLaboralesException(String arg0) {
		super(arg0);
	}

	public FaltanSituacionesLaboralesException(Throwable arg0) {
		super(arg0);
	}

}
