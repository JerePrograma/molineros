package ar.com.ospim.afiliados.action;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.util.ArrayList;
import java.util.Iterator;

import ar.com.ospim.afiliados.beans.Afiliado;
import ar.com.ospim.util.ConnectionHelper;

public class CorrijeCuilsNulos {

	/**
	 * @param args
	 */
	public static void main(String[] args) {
		
		Connection con = null;
		PreparedStatement stmt = null, stmt1 = null;
		Afiliado afi = null;
		ArrayList<Afiliado> afiliados = new ArrayList<Afiliado>();
		
		try {	
			con = ConnectionHelper.getConnectionFromJavaApplication() ; 
			
			String sql = "select documento_tipo, docu_numero, sexo from afiliado where cuil is null";

			stmt = con.prepareStatement(sql.toString());
			ResultSet rs = stmt.executeQuery();
		
			while(rs.next()){
				afi = new Afiliado();
				afi.setDocu_numero(rs.getString("docu_numero"));
				afi.setDocumento_tipo(rs.getString("documento_tipo"));
				afi.setSexo(rs.getString("sexo"));
				
				afiliados.add(afi);
			}
			System.out.println("cantidad de afiliados: " + afiliados.size());
			
			for (Iterator iterator = afiliados.iterator(); iterator.hasNext();) {
				Afiliado afiliado = (Afiliado) iterator.next();
				
				String cuil = GeneraCuil.generar(Integer.parseInt(afiliado.getDocu_numero()), afiliado.getSexo().equalsIgnoreCase("m")?'m':'f');	
			
			
				String sql1 = "update afiliado set cuil = ? where documento_tipo = ? and docu_numero = ?;";
				stmt1 = con.prepareStatement(sql1);
				stmt1.setString(1, cuil);
				stmt1.setString(2, afiliado.getDocumento_tipo());
				stmt1.setString(3, afiliado.getDocu_numero());
				stmt1.executeUpdate();
				
				System.out.println("Afiliado tdoc: "+ afiliado.getDocumento_tipo() + " numero: " + afiliado.getDocu_numero() + " cuil generado: " + cuil);
			}
		} catch (Exception ex) {
			System.err.println("Error: " + ex);
		} finally {
			ConnectionHelper.cerrar(con);
			ConnectionHelper.cerrar(stmt);
			ConnectionHelper.cerrar(stmt1);
			
		}
		return;
	}

}

