package ar.com.ospim.liquidaciones;

public class AnticiposReUtilizadosException extends Exception {

	private static final long serialVersionUID = 1L;

	public AnticiposReUtilizadosException() {
		super();
	}

	public AnticiposReUtilizadosException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public AnticiposReUtilizadosException(String arg0) {
		super(arg0);
	}

	public AnticiposReUtilizadosException(Throwable arg0) {
		super(arg0);
	}

}
