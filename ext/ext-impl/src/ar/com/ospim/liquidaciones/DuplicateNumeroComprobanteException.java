package ar.com.ospim.liquidaciones;

public class DuplicateNumeroComprobanteException extends Exception {

	/**
	 * 
	 */
	private static final long serialVersionUID = 1L;

	public DuplicateNumeroComprobanteException() {
		super();
	}

	public DuplicateNumeroComprobanteException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public DuplicateNumeroComprobanteException(String arg0) {
		super(arg0);
	}

	public DuplicateNumeroComprobanteException(Throwable arg0) {
		super(arg0);
	}

}
