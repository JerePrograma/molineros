package ar.com.ospim.global;

public class ComprobanteExistenteException extends Exception {

	/**
	 * 
	 */
	private static final long serialVersionUID = 1L;

	public ComprobanteExistenteException() {
		super();
	}

	public ComprobanteExistenteException(String message, Throwable cause) {
		super(message, cause);
	}

	public ComprobanteExistenteException(String message) {
		super(message);
	}

	public ComprobanteExistenteException(Throwable cause) {
		super(cause);
	}

}
