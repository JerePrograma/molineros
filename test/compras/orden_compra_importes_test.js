const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const jsp = fs.readFileSync(path.resolve(__dirname, '../../ext-web/docroot/html/portlet/compras/requerimientos/requerimiento_compra_orden.jsp'), 'latin1');
let script = jsp.slice(jsp.indexOf('function <portlet:namespace />importeCentavosOrdenCompra'), jsp.lastIndexOf('</script>'));
script = script.replace(/<%[\s\S]*?%>/g, '').replace(/<portlet:namespace \/>/g, 'comprasTest_');
script = script.replace(/^comprasTest_calcularOrdenCompra\(\);\s*$/m, '');
const context = {};
vm.createContext(context);
vm.runInContext(script, context);
const centavos = context.comprasTest_importeCentavosOrdenCompra;
const sumar = context.comprasTest_sumarCentavosOrdenCompra;
const multiplicar = context.comprasTest_multiplicarCentavosOrdenCompra;
const mostrar = context.comprasTest_mostrarCentavosOrdenCompra;
assert.strictEqual(centavos('99999999999999.99'), '9999999999999999');
assert.strictEqual(mostrar(centavos('99999999999999.99')), '99999999999999.99');
assert.strictEqual(mostrar(sumar(centavos('0.10'), centavos('0.20'))), '0.30');
assert.strictEqual(mostrar(multiplicar(centavos('1234,56'), 3)), '3703.68');
assert.strictEqual(mostrar(multiplicar(centavos('999999.99'), 1000000000)), '999999990000000.00');
assert.strictEqual(mostrar(sumar('9999999999999999', '1')), '100000000000000.00');
assert.strictEqual(centavos('000,01'), '1');
assert.strictEqual(centavos('1.234,56'), null);
assert.strictEqual(centavos('-1'), null);
assert.strictEqual(centavos('1e2'), null);
assert.strictEqual(centavos('1.234'), null);
assert.ok(jsp.includes('if (ordenEditable && !ordenMedica)'));
console.log('ORDEN_COMPRA_IMPORTES_ES5_OK checks=12');
