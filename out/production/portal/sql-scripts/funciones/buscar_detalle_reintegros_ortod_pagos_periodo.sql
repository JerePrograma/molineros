 where 
--op
 opo.alta_fecha >= (cast ($1 as timestamp without time zone) - interval '1 months') and
 opo.alta_fecha < $1 and
 opo.baja_fecha is null and
 opo.id_orden_pago = opol.id_orden_pago_ospim and
 opol.id_lista_reintegro_pago = lrpd.id_lista_reintegro_pago and
 lrpd.id_reintegro = dc.id_cuota and 
 dc.id_reintegro = r.id_reintegro and 
